"""Keep the README's model and retrieval results in step with ml/reports.

    python -m ml.readme_metrics            # rewrite the generated block
    python -m ml.readme_metrics --check    # exit 1 if the README is stale

The block between the ``metrics:start`` / ``metrics:end`` markers is built
from ``ml/reports/metrics.json`` (``python -m ml.train``) and
``ml/reports/rag_metrics.json`` (``python -m ml.rag.evaluate``). A test runs
the check, so CI fails whenever a retrain or re-evaluation changes the
numbers and the README isn't regenerated.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
REPORTS = ROOT / "ml" / "reports"
START = "<!-- metrics:start (generated by `python -m ml.readme_metrics`; do not edit by hand) -->"
END = "<!-- metrics:end -->"
_BLOCK = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)


def shield(label: str, message: str, color: str = "blue") -> str:
    """A shields.io static badge URL (dashes and underscores escaped)."""
    def esc(text: str) -> str:
        return quote(text.replace("-", "--").replace("_", "__").replace(" ", "_"), safe="")
    return f"https://img.shields.io/badge/{esc(label)}-{esc(message)}-{color}"


def pct_lower(model: float, baseline: float) -> float:
    return round(100 * (baseline - model) / baseline, 1)


def render(model: dict, rag: dict) -> str:
    test = model["test"]
    m, b = test["model"], test["baseline"]
    season = model["split"]["test_target_season"]
    overall = pct_lower(m["overall"]["mae"], b["overall"]["mae"])
    relevant = pct_lower(m["relevant"]["mae"], b["relevant"]["mae"])
    inj = rag["injury_ranking"]
    hit = round(100 * inj["hit_at_1/injury_query"])
    recency = round(100 * inj["hit_at_1/most_recent_first"])

    badges = " ".join([
        f"[![Projection model]({shield('projection error', f'{overall}% below baseline')})](ml/reports/REPORT.md)",
        f"[![Injury retrieval]({shield('RAG hit@1', f'{hit}% vs {recency}% recency')})](ml/reports/RAG_REPORT.md)",
    ])
    rows = [
        "| Result | This project | Simple baseline | |",
        "|---|---|---|---|",
        f"| Projection error, held-out {season} season (MAE, PPR pts/game) | **{m['overall']['mae']}** "
        f"| {b['overall']['mae']} (same as last season) | {overall}% lower |",
        f"| … fantasy-relevant players (≥ 10 PPG) | **{m['relevant']['mae']}** "
        f"| {b['relevant']['mae']} | {relevant}% lower |",
        f"| Ranking accuracy (Spearman) | **{m['overall']['spearman']}** | {b['overall']['spearman']} | |",
        f"| RAG: worst injury season ranked first (hit@1, {inj['n']} players) "
        f"| **{100 * inj['hit_at_1/injury_query']:.1f}%** "
        f"| {100 * inj['hit_at_1/most_recent_first']:.1f}% (most recent first) | |",
    ]
    return "\n".join([START, badges, "", *rows, END])


def load_reports(reports: Path = REPORTS) -> tuple[dict, dict]:
    def read(name):
        return json.loads((reports / name).read_text(encoding="utf-8"))
    return read("metrics.json"), read("rag_metrics.json")


def updated(readme_text: str, block: str) -> str:
    if not _BLOCK.search(readme_text):
        raise ValueError("README has no metrics:start / metrics:end block")
    return _BLOCK.sub(lambda _: block, readme_text, count=1)


def main(argv=None, readme: Path = README, reports: Path = REPORTS) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the README is out of date")
    args = parser.parse_args(argv)
    text = readme.read_text(encoding="utf-8")
    new = updated(text, render(*load_reports(reports)))
    if args.check:
        if new != text:
            print("README metrics are stale: run `python -m ml.readme_metrics`", file=sys.stderr)
            return 1
        return 0
    if new != text:
        readme.write_text(new, encoding="utf-8")
        print("README metrics updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
